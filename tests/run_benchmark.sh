#!/usr/bin/env bash
#
# run_benchmark.sh - speed and memory table for one or more model files.
#
# Usage (from the project root):
#   bash tests/run_benchmark.sh models/stories42M.bin models/gguf/tinyllama.gguf
#   make bench                      (every model in models/ and models/gguf/)
#
# Each model is run with 1 thread and with all cores (OMP_NUM_THREADS),
# 3 times each; the median tokens/s is reported. Output:
#   - a table on the screen
#   - documentation/PERFORMANCE_RESULTS.md (with CPU, RAM, compiler, date)
#
# Environment: PROMPT=32 GEN=64 RUNS=3 to change the workload.

set -u
cd "$(dirname "$0")/.." || exit 1

PROMPT="${PROMPT:-32}"
GEN="${GEN:-64}"
RUNS="${RUNS:-3}"
OUT="documentation/PERFORMANCE_RESULTS.md"

if [ "$#" -eq 0 ]; then
    echo "Usage: bash tests/run_benchmark.sh <model file> [more model files...]"
    exit 1
fi

make build/llm_bench >/dev/null || exit 1
mkdir -p documentation

CORES=$(nproc 2>/dev/null || echo 1)
CPU=$(grep -m1 "model name" /proc/cpuinfo 2>/dev/null | cut -d: -f2- | sed 's/^ *//')
RAM=$(awk '/MemTotal/ {printf "%.1f GB", $2 / 1048576}' /proc/meminfo 2>/dev/null)
CC_VERSION=$(gcc --version | head -1)

median() { sort -n | awk '{a[NR] = $1} END {print a[int((NR + 1) / 2)]}'; }

ROWS=""
for MODEL in "$@"; do
    if [ ! -f "$MODEL" ]; then
        echo "skip: $MODEL not found"
        continue
    fi
    THREAD_LIST="1"
    [ "$CORES" -gt 1 ] && THREAD_LIST="1 $CORES"
    for T in $THREAD_LIST; do
        echo "running $(basename "$MODEL") with $T thread(s) x $RUNS ..."
        LINES=""
        for _ in $(seq "$RUNS"); do
            L=$(OMP_NUM_THREADS="$T" ./build/llm_bench "$MODEL" "$PROMPT" "$GEN" --csv 2>/tmp/llm_bench_err)
            if [ -z "$L" ]; then
                echo "  FAIL: $(cat /tmp/llm_bench_err)"
                continue 2
            fi
            LINES="$LINES$L"$'\n'
        done
        LAST=$(printf "%s" "$LINES" | tail -n1)
        IFS=, read -r NAME FMT THR FILE_MB KV_MB ACT_MB RSS_LOAD RSS_PEAK LOAD_S _ _ <<< "$LAST"
        P_MED=$(printf "%s" "$LINES" | cut -d, -f10 | median)
        G_MED=$(printf "%s" "$LINES" | cut -d, -f11 | median)
        ROWS="$ROWS| $NAME | $FMT | $THR | $FILE_MB | $KV_MB | $ACT_MB | $RSS_PEAK | $LOAD_S | $P_MED | $G_MED |"$'\n'
    done
done

if [ -z "$ROWS" ]; then
    echo "No model could be measured."
    exit 1
fi

HEADER="| Model | Format | Threads | File (MB) | KV cache (MB) | Activations (MB) | Peak RSS (MB) | Load (s) | Prompt (tok/s) | Generation (tok/s) |
|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"

{
    echo "# Performance results"
    echo
    echo "Generated by \`tests/run_benchmark.sh\` on $(date '+%Y-%m-%d %H:%M')."
    echo
    echo "- CPU: ${CPU:-unknown} ($CORES logical cores)"
    echo "- RAM: ${RAM:-unknown}"
    echo "- Compiler: $CC_VERSION, flags \`-O2 -fopenmp\`"
    echo "- Workload: $PROMPT prompt tokens + $GEN generated tokens (greedy),"
    echo "  KV cache allocated for $((PROMPT + GEN)) positions; median of $RUNS runs."
    echo
    echo "$HEADER"
    printf "%s" "$ROWS"
    echo
    echo "Column meaning: see documentation/PERFORMANCE.md."
} > "$OUT"

echo
echo "$HEADER"
printf "%s" "$ROWS"
echo
echo "Written to $OUT"
